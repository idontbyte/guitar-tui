    private static void AppendTriadLookup(StringBuilder builder, TriadInversionLibrary triads, ChordQuality quality)
    {
        builder.AppendLine($"<section class=\"page\">");
        builder.AppendLine($"<h2>Fast {Html(quality.ToString().ToLowerInvariant())} triad lookup</h2>");
        builder.AppendLine($"<p class=\"hint\">Formula: {Html(quality == ChordQuality.Major ? "R 3 5" : "R b3 5")}. Frets are listed high-to-low inside each string set.</p>");
        builder.AppendLine("<table class=\"lookup\"><thead><tr><th>Root</th><th>Notes</th><th>E B G</th><th>B G D</th><th>G D A</th><th>D A E</th></tr></thead><tbody>");

        foreach (var root in MusicTheory.ChromaticRoots)
        {
            var groupings = triads.GetTriadInversions(root, quality).ToDictionary(grouping => grouping.Name);
            builder.AppendLine("<tr>");
            builder.AppendLine($"<td class=\"root-cell\">{Html(root)}</td>");
            builder.AppendLine($"<td>{Html(TriadNotes(root, quality))}</td>");
            foreach (var groupingName in new[] { "E B G", "B G D", "G D A", "D A E" })
            {
                builder.AppendLine($"<td>{GripText(groupings[groupingName])}</td>");
            }
            builder.AppendLine("</tr>");
        }

        builder.AppendLine("</tbody></table>");
        builder.AppendLine("</section>");
    }

    private static void AppendModificationCheats(StringBuilder builder)
    {
        builder.AppendLine("<section class=\"page\">");
        builder.AppendLine("<h2>Shape modification cheats</h2>");
        builder.AppendLine("<div class=\"grid-2\">");
        builder.AppendLine("<div><h3>Start from major</h3><ul>");
        builder.AppendLine("<li><b>minor</b>: lower the 3 one fret.</li>");
        builder.AppendLine("<li><b>sus4</b>: raise the 3 one fret.</li>");
        builder.AppendLine("<li><b>augmented</b>: raise the 5 one fret.</li>");
        builder.AppendLine("<li><b>major 7</b>: add 7 one fret below the root, or replace the root with 7 for a rootless color.</li>");
        builder.AppendLine("<li><b>dominant 7</b>: add b7 two frets below the root, or replace the root with b7 for a rootless color.</li>");
        builder.AppendLine("</ul></div>");
        builder.AppendLine("<div><h3>Start from minor</h3><ul>");
        builder.AppendLine("<li><b>diminished</b>: lower the 5 one fret.</li>");
        builder.AppendLine("<li><b>minor 7</b>: add b7 two frets below the root.</li>");
        builder.AppendLine("<li><b>m7b5</b>: minor 7 with the 5 lowered one fret.</li>");
        builder.AppendLine("<li><b>m6</b>: add 6 three frets below the root or nine frets above it.</li>");
        builder.AppendLine("<li><b>add9</b>: keep the triad and add 9 two frets above the root.</li>");
        builder.AppendLine("</ul></div>");
        builder.AppendLine("</div>");
        builder.AppendLine("<h2>Practice loop</h2>");
        builder.AppendLine("<ol>");
        builder.AppendLine("<li>Pick a song progression and reduce every chord to major, minor, diminished, or a color shortcut.</li>");
        builder.AppendLine("<li>Choose one string set and play the nearest inversion for each chord.</li>");
        builder.AppendLine("<li>Repeat on another string set, keeping the movement as small as possible.</li>");
        builder.AppendLine("<li>Add one color note for every 7, maj7, m7, 6, or m6 chord after the triads feel automatic.</li>");
        builder.AppendLine("</ol>");
        builder.AppendLine("</section>");
    }

    private static string GripText(TriadGroupingResult grouping)
    {
        var labels = new Dictionary<string, string>
        {
            ["Root"] = "R",
            ["1st inv"] = "1",
            ["2nd inv"] = "2"
        };

        return string.Join(
            string.Empty,
            grouping.Shapes.Select(shape =>
            {
                var frets = shape.Diagram.Positions
                    .OrderBy(position => position.StringIndex)
                    .Select(position => position.Fret.ToString());
                var functions = shape.Diagram.Positions
                    .OrderBy(position => position.StringIndex)
                    .Select(position => position.Label);
                var label = labels.GetValueOrDefault(shape.InversionName, shape.InversionName);
                return $"<span class=\"grip\"><span class=\"inv\">{Html(label)}</span>{Html(string.Join("-", frets))}<span class=\"functions\">{Html(string.Join("-", functions))}</span></span>";
            }));
    }

    private static string TriadNotes(string root, ChordQuality quality)
    {
        var intervals = quality == ChordQuality.Major ? new[] { "R", "3", "5" } : ["R", "b3", "5"];
        return Notes(root, intervals);
    }

    private static string Notes(string root, IReadOnlyList<string> intervals)
    {
        return string.Join(" ", intervals.Select(interval => Name(root, interval)));
    }

    private static string Name(string root, string interval) => MusicTheory.NameForInterval(root, interval);

    private static string Html(string value) => WebUtility.HtmlEncode(value);

    private sealed record GuitarString(string Name, int PitchClass);

    private sealed record ChordShortcut(string Symbol, string Formula, string TriadCore, string FastIdea);
}
