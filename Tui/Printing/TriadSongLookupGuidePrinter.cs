    private static void AppendNoteMap(StringBuilder builder)
    {
        builder.AppendLine("<section>");
        builder.AppendLine("<h2>Fretboard note map, frets 0-12</h2>");
        builder.AppendLine("<table class=\"note-map\"><thead><tr><th>String</th>");
        for (var fret = 0; fret <= 12; fret++)
        {
            builder.AppendLine($"<th>{fret}</th>");
        }
        builder.AppendLine("</tr></thead><tbody>");

        foreach (var guitarString in Tuning)
        {
            builder.AppendLine("<tr>");
            builder.AppendLine($"<td class=\"string\">{Html(guitarString.Name)}</td>");
            for (var fret = 0; fret <= 12; fret++)
            {
                var note = MusicTheory.NameFor(guitarString.PitchClass + fret);
                builder.AppendLine($"<td{(fret == 0 || fret == 12 ? " class=\"root\"" : string.Empty)}>{Html(note)}</td>");
            }
            builder.AppendLine("</tr>");
        }

        builder.AppendLine("</tbody></table>");
        builder.AppendLine("</section>");
    }

