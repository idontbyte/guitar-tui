        var builder = StartHtml("Triad song-chord lookup guide");
        builder.AppendLine("<h1>Triad song-chord lookup guide</h1>");
        builder.AppendLine($"<div class=\"subtitle\">Generated by guitar-tui on {DateTime.Now:yyyy-MM-dd HH:mm}</div>");
        builder.AppendLine("<p class=\"hint\"><b>Fast use:</b> read the song chord, choose the triad core, find that root in the lookup table, then pick a string set near your hand. For E7, Am, G: use E major triads plus D as b7, A minor triads, and G major triads.</p>");

        AppendNoteMap(builder);
        AppendHowToRead(builder);
        AppendChordShortcutTable(builder);
        AppendUpperTriadTable(builder);
        AppendTriadLookup(builder, triads, ChordQuality.Major);
        AppendTriadLookup(builder, triads, ChordQuality.Minor);
        AppendModificationCheats(builder);

        builder.AppendLine("</body>");
        builder.AppendLine("</html>");
        return builder.ToString();
    }

