    public static string Print(TriadInversionLibrary triads)
    {
        var filePath = Path.Combine(Path.GetTempPath(), "guitar-tui-triad-song-chord-lookup-guide.html");
        File.WriteAllText(filePath, BuildHtml(triads));
        Open(filePath);
        return filePath;
    }

    private static void Open(string filePath)
    {
        if (OperatingSystem.IsMacOS())
        {
            Process.Start(new ProcessStartInfo
            {
                FileName = "open",
                UseShellExecute = false,
                CreateNoWindow = true,
                ArgumentList = { filePath }
            });
        }
        else
        {
            Process.Start(new ProcessStartInfo
            {
                FileName = filePath,
                UseShellExecute = true
            });
        }
    }

